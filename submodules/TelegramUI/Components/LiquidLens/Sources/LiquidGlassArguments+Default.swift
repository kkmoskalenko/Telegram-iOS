import LiquidLensSharedTypes

extension LiquidGlassArguments {
    
    public static func `default`(
        resolution: SIMD2<Float> = .zero,
        dpr: Float = 1,
        mouse: SIMD2<Float>? = nil,
        mouseSpring: SIMD2<Float>? = nil,
        refThickness: Float = 20,
        refFactor: Float = 1.4,
        refDispersion: Float = 7,
        refFresnelRange: Float = 30,
        refFresnelHardness: Float = 0.2,
        refFresnelFactor: Float = 0.2,
        glareRange: Float = 30,
        glareHardness: Float = 0.2,
        glareFactor: Float = 0.9,
        glareConvergence: Float = 0.5,
        glareOppositeFactor: Float = 0.8,
        glareAngle: Float = -45 * .pi / 180,
        blurRadius: Int32 = 1,
        tint: SIMD4<Float> = [1, 1, 1, 0],
        shadowExpand: Float = 25,
        shadowFactor: Float = 0.15,
        shadowPosition: SIMD2<Float> = [0, -10],
        bgType: Int32 = 4,
        bgTextureReady: Bool = false,
        bgTextureRatio: Float = 1,
        contentOrigin: SIMD2<Float> = .zero,
        contentSize: SIMD2<Float> = .zero,
        shapeWidth: Float = 200,
        shapeHeight: Float = 200,
        shapeRadius: Float = 80,
        shapeRoundness: Float = 5,
        mergeRate: Float = 0.05,
        showShape1: Bool = false,
        step: Int32 = 9
    ) -> LiquidGlassArguments {
        LiquidGlassArguments(
            resolution: resolution,
            dpr: dpr,
            mouse: mouse ?? 0.5 * resolution,
            mouseSpring: mouseSpring ?? 0.5 * resolution,
            refThickness: refThickness,
            refFactor: refFactor,
            refDispersion: refDispersion,
            refFresnelRange: refFresnelRange,
            refFresnelHardness: refFresnelHardness,
            refFresnelFactor: refFresnelFactor,
            glareRange: glareRange,
            glareHardness: glareHardness,
            glareFactor: glareFactor,
            glareConvergence: glareConvergence,
            glareOppositeFactor: glareOppositeFactor,
            glareAngle: glareAngle,
            blurRadius: blurRadius,
            tint: tint,
            shadowExpand: shadowExpand,
            shadowFactor: shadowFactor,
            shadowPosition: shadowPosition,
            bgType: bgType,
            bgTextureReady: bgTextureReady ? 1 : 0,
            bgTextureRatio: bgTextureRatio,
            contentOrigin: contentOrigin,
            contentSize: contentSize,
            shapeWidth: shapeWidth,
            shapeHeight: shapeHeight,
            shapeRadius: shapeRadius,
            shapeRoundness: shapeRoundness,
            mergeRate: mergeRate,
            showShape1: showShape1 ? 1 : 0,
            step: step
        )
    }
}
